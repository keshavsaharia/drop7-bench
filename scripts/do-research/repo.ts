const FORBIDDEN_PREFIXES = ["0x7d", "0xd7"]; // protected and final cohorts: never allocatable

export interface LeasePool {
  startHex: string;
  endExclusiveHex: string;
}

function allKnownConstants(): Set<number> {
  // Every 8-hex-digit constant already present in the tree, as the lease map prescribes.
  const out = spawnSync("bash", ["-c", "grep -rhoE '0x[0-9a-fA-F]{8}' docs approaches src research artifacts 2>/dev/null | sort -u"], { cwd: REPO_ROOT, encoding: "utf8", maxBuffer: 64 * 1024 * 1024 });
  const set = new Set<number>();
  for (const line of (out.stdout || "").split("\n")) {
    if (line) set.add(Number.parseInt(line, 16));
  }
  return set;
}

function existingLeaseRanges(): Array<[number, number]> {
  return listRecords("seeds/leases").map((l) => [Number.parseInt(l.rangeStartHex, 16), Number.parseInt(l.rangeEndExclusiveHex, 16)] as [number, number]);
}

export interface LeaseGrant {
  seedLeaseId: string;
  rangeStartHex: string;
  rangeEndExclusiveHex: string;
  role: string;
  path: string;
}

/**
 * Grants the next free block of `count` seeds from the pool, skipping any
 * seed that is an existing constant or inside an existing lease, and refuses
 * forbidden prefixes.  Writes the SL record (state reserved) and a row in the
 * lease map.  Returns null when the pool cannot satisfy the request.
 */
export function allocateLease(pool: LeasePool, count: number, role: string, experimentId: string, purpose: string): LeaseGrant | null {
  const start = Number.parseInt(pool.startHex, 16);
  const end = Number.parseInt(pool.endExclusiveHex, 16);
  for (const prefix of FORBIDDEN_PREFIXES) {
    if (pool.startHex.toLowerCase().startsWith(prefix) || pool.endExclusiveHex.toLowerCase().startsWith(prefix)) {
      throw new Error(`lease pool ${pool.startHex} touches a forbidden prefix ${prefix}`);
    }
  }
  const constants = allKnownConstants();
  const ranges = existingLeaseRanges();
  const blocked = (seed: number) => constants.has(seed) || ranges.some(([a, b]) => seed >= a && seed < b);
  // Align blocks to 256 seeds so ranges stay readable in hex.
  for (let candidate = Math.ceil(start / 256) * 256; candidate + count <= end; candidate += 256) {
    let clean = true;
    for (let seed = candidate; seed < candidate + count; seed += 1) {
      if (blocked(seed)) { clean = false; break; }
    }
    if (!clean) continue;
    const id = `SL-${isoNow().replace(/[-:]/g, "")}-${candidate.toString(16).padStart(8, "0")}`;
    const record = {
      $schema: "../schemas/seed-lease-v1.schema.json",
      format: "drop7-seed-lease-v1",
      seedLeaseId: id,
      experimentId,
      rngAlgorithm: "mulberry32 with mix32 domain separation (src/core/native/engine.hpp); headless disc stream kNextDiscDomain, reveal stream kRevealDomain",
      domain: "environment",
      role,
      rangeStartHex: `0x${candidate.toString(16).padStart(8, "0")}`,
      rangeEndExclusiveHex: `0x${(candidate + count).toString(16).padStart(8, "0")}`,
      cohortManifestSha256: null,
      state: "reserved",
      reservedAt: isoNow(),
      openedAt: null,
      closedAt: null,
      protocolSha256: null,
      runIds: [],
      notes: [
        `Allocated by scripts/do-research from pool ${pool.startHex}-${pool.endExclusiveHex} after scanning every 8-hex-digit constant under docs/, approaches/, src/, research/ and artifacts/ and every research/seeds/leases record; the block overlaps none of them and no protected (0x7d) or final (0xd7) prefix.`,
        `Purpose: ${purpose}. Once read, the role is permanent: ${role} data can never become confirmation evidence.`,
      ],
    };
    const rel = `research/seeds/leases/${id}.json`;
    writeJson(rel, record);
    appendLeaseMapRow(record.seedLeaseId, record.rangeStartHex, record.rangeEndExclusiveHex, count, role, experimentId);
    return { seedLeaseId: id, rangeStartHex: record.rangeStartHex, rangeEndExclusiveHex: record.rangeEndExclusiveHex, role, path: rel };
  }
  return null;
}

function appendLeaseMapRow(id: string, startHex: string, endHex: string, count: number, role: string, experimentId: string): void {
  const full = path.join(REPO_ROOT, "docs/exploratory/lease-map.md");
  let text = readFileSync(full, "utf8");
  const header = "## Orchestrator allocations (scripts/do-research)";
  if (!text.includes(header)) {
    text += `\n${header}\n\nEach row was written by the allocator before any seed in it was read.\n\n| Lease | Range | Games | Role | Consumer | State |\n| --- | --- | ---: | --- | --- | --- |\n`;
  }
  const endInclusive = `0x${(Number.parseInt(endHex, 16) - 1).toString(16).padStart(8, "0")}`;
  text = text.replace(/\n*$/, "\n") + `| \`${id}\` | \`${startHex}\`–\`${endInclusive}\` | ${count} | ${role} | ${experimentId} | reserved |\n`;
  writeFileSync(full, text);
}

