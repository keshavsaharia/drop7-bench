// Repository access for ./do-research: planning context, record creation,
// and the seed-lease allocator.  Everything here is deliberately conservative:
// the allocator refuses protected/final prefixes outright, refuses any range
// that overlaps an existing lease record or any 8-hex-digit constant already
// in the tree, and records every grant in research/seeds/leases/ and the
// lease map before a single seed can be read.

import { execFileSync, spawnSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { randomBytes } from "node:crypto";

export const REPO_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
export const RESEARCHCTL = path.join(REPO_ROOT, ".agents/skills/million-point-research/scripts/researchctl.py");

export function isoNow(): string {
  return new Date().toISOString().replace(/\.\d{3}Z$/, "Z");
}

export function readText(relative: string, limitLines?: number): string {
  const full = path.join(REPO_ROOT, relative);
  if (!existsSync(full)) return "";
  const text = readFileSync(full, "utf8");
  if (!limitLines) return text;
  return text.split("\n").slice(0, limitLines).join("\n");
}

export function readJson<T = any>(relative: string): T | null {
  const full = path.isAbsolute(relative) ? relative : path.join(REPO_ROOT, relative);
  if (!existsSync(full)) return null;
  return JSON.parse(readFileSync(full, "utf8")) as T;
}

export function writeJson(relative: string, value: unknown): void {
  const full = path.isAbsolute(relative) ? relative : path.join(REPO_ROOT, relative);
  mkdirSync(path.dirname(full), { recursive: true });
  writeFileSync(full, JSON.stringify(value, null, 2) + "\n");
}

export function listRecords<T = any>(subdir: string): Array<T & { $path: string }> {
  const dir = path.join(REPO_ROOT, "research", subdir);
  if (!existsSync(dir)) return [];
  return readdirSync(dir)
    .filter((name) => name.endsWith(".json"))
    .sort()
    .map((name) => ({ ...(readJson<T>(path.join(dir, name)) as T), $path: `research/${subdir}/${name}` }));
}

export function listFamilies(): string[] {
  return readdirSync(path.join(REPO_ROOT, "approaches"), { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .map((entry) => entry.name)
    .sort();
}

function mdxSummary(relative: string): string {
  const text = readText(relative);
  if (!text) return "";
  const front = text.match(/^---\n([\s\S]*?)\n---/);
  const headings = text.split("\n").filter((line) => /^#{2,3} /.test(line)).slice(0, 20);
  return `${relative}\n${front ? front[1] : ""}\n${headings.join("\n")}`;
}

export interface HistoryEntry {
  iteration: number;
  theoryId?: string;
  experimentId?: string;
  title: string;
  outcome: string;
  notes: string;
}

/** The brief the planner reads.  Only retained repository text, no numbers of our own. */
export function gatherContext(history: HistoryEntry[], focus: string | undefined): string {
  const theories = listRecords("theories").map((t) => `- ${t.theoryId}: ${t.title} [${t.lifecycle}/${t.assessment}/${t.evidenceTier}]`);
  const experiments = listRecords("experiments").map((e) => `- ${e.experimentId}: ${e.title} [${e.benchmarkTier}/${e.lifecycle}]`);
  const results = listRecords("results").map((r) => `- ${r.resultId} (${r.experimentId}): ${r.runValidity}/${r.scientificOutcome}/${r.evidenceTier} — ${String(r.summary).slice(0, 400)}`);
  const leases = listRecords("seeds/leases").map((l) => `- ${l.seedLeaseId}: ${l.rangeStartHex}-${l.rangeEndExclusiveHex} ${l.role} ${l.state}`);
  const logDir = path.join(REPO_ROOT, "web/content/log");
  const logs = existsSync(logDir) ? readdirSync(logDir).filter((n) => n.endsWith(".mdx")).sort().slice(-2) : [];
  const doctor = spawnSync("python3", [RESEARCHCTL, "doctor"], { cwd: REPO_ROOT, encoding: "utf8" });
  const parts = [
    "# Planning brief (generated by ./do-research; every line is quoted from the repository)",
    focus ? `\n## Operator focus\n${focus}` : "",
    "\n## docs/research/status.md (head)\n" + readText("docs/research/status.md", 230),
    "\n## docs/research/roadmap.md priority map\n" + readText("docs/research/roadmap.md", 60),
    "\n## Theories\n" + theories.join("\n"),
    "\n## Experiments\n" + experiments.join("\n"),
    "\n## Results\n" + results.join("\n"),
    "\n## Seed leases on record\n" + leases.join("\n"),
    "\n## Lease map (docs/exploratory/lease-map.md allocation table)\n" + readText("docs/exploratory/lease-map.md").split("\n").filter((l) => l.startsWith("|")).join("\n"),
    "\n## Recent research log entries\n" + logs.map((n) => mdxSummary(`web/content/log/${n}`)).join("\n\n"),
    "\n## Approach families\n" + listFamilies().join(", "),
    "\n## Machine (researchctl doctor)\n" + (doctor.stdout || "").slice(0, 3000),
    "\n## This orchestrator's earlier iterations\n" + (history.length ? history.map((h) => `- iteration ${h.iteration}: ${h.title} → ${h.outcome}. ${h.notes}`).join("\n") : "(none)"),
  ];
  return parts.join("\n");
}

