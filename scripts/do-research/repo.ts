function researchctl(args: string[]): string {
  return execFileSync("python3", [RESEARCHCTL, ...args], { cwd: REPO_ROOT, encoding: "utf8" });
}

function createdPath(output: string, prefix: string): string {
  const line = output.split("\n").map((l) => l.trim()).filter((l) => l.includes(prefix)).pop();
  if (!line) throw new Error(`researchctl did not report a ${prefix} path: ${output}`);
  return line.replace(/^created\s+/i, "").trim();
}

export function createTheory(args: { slug: string; title: string; claim: string; mechanism: string; falsification: string[]; platform: string; model: string }): { id: string; path: string } {
  const out = researchctl(["new", "theory", "--slug", args.slug, "--title", args.title, "--claim", args.claim, "--mechanism", args.mechanism, "--falsification", args.falsification[0] ?? "unspecified", "--information-class", "public-policy", "--platform", args.platform, "--model", args.model]);
  const rel = createdPath(out, "research/theories/");
  const record = readJson(rel);
  record.falsificationCriteria = args.falsification;
  record.lifecycle = "proposed";
  record.updatedAt = isoNow();
  writeJson(rel, record);
  return { id: record.theoryId, path: rel };
}

export function createExperiment(args: { slug: string; title: string; theoryId: string; hypothesis: string; candidate: string; entryPoint: string; classification: string; platform: string; model: string; patch: Record<string, unknown> }): { id: string; path: string } {
  const out = researchctl(["new", "experiment", "--slug", args.slug, "--title", args.title, "--theory-id", args.theoryId, "--hypothesis", args.hypothesis, "--candidate", args.candidate, "--entry-point", args.entryPoint, "--classification", args.classification, "--information-boundary", "public-policy", "--platform", args.platform, "--model", args.model]);
  const rel = createdPath(out, "research/experiments/");
  const record = readJson(rel);
  Object.assign(record, args.patch);
  record.updatedAt = isoNow();
  writeJson(rel, record);
  return { id: record.experimentId, path: rel };
}

export function createContribution(args: { summary: string; level: string; role: string; degree: string; platform: string; model: string; theoryId?: string; experimentId?: string; artifacts: string[]; validation: string[] }): string {
  const cli = ["new", "contribution", "--summary", args.summary, "--level", args.level, "--role", args.role, "--degree", args.degree, "--platform", args.platform, "--model", args.model];
  if (args.theoryId) cli.push("--theory-id", args.theoryId);
  if (args.experimentId) cli.push("--experiment-id", args.experimentId);
  for (const a of args.artifacts) cli.push("--artifact", a);
  for (const v of args.validation) cli.push("--validation", v);
  const out = researchctl(cli);
  const rel = createdPath(out, "research/contributions/");
  return readJson(rel).contributionId;
}

export function validateRecords(): { ok: boolean; output: string } {
  const result = spawnSync("make", ["research-validate"], { cwd: REPO_ROOT, encoding: "utf8" });
  return { ok: result.status === 0, output: (result.stdout || "") + (result.stderr || "") };
}

export function newRunId(prefix: string): string {
  return `${prefix}-${isoNow().replace(/[-:]/g, "")}-${randomBytes(4).toString("hex")}`;
}

export function gitShort(): string {
  try {
    return execFileSync("git", ["rev-parse", "--short", "HEAD"], { cwd: REPO_ROOT, encoding: "utf8" }).trim();
  } catch {
    return "unknown";
  }
}
